#!/usr/bin/env node
/**
 * Generates src/lib/strengthData.ts (the lazily loaded dictionaries for the passphrase
 * strength estimate) from zxcvbn 4.4.2's MIT-licensed frequency lists.
 *
 *   mkdir /tmp/zx && cd /tmp/zx && npm pack zxcvbn@4.4.2 && tar xzf zxcvbn-4.4.2.tgz
 *   node scripts/build-strength-data.mjs /tmp/zx/package/lib/frequency_lists.js
 *
 * The input is parsed as text (it is never executed).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-strength-data.mjs <path to zxcvbn/lib/frequency_lists.js>');
  process.exit(1);
}
const text = readFileSync(src, 'utf8');

function list(name) {
  const m = text.match(new RegExp(`\\b${name}: "([^"]*)"`));
  if (!m) throw new Error(`list ${name} not found`);
  return m[1].split(',').filter((w) => /^[a-z0-9]+$/.test(w));
}

const LIMITS = { passwords: 8000, english_wikipedia: 7000, female_names: 1000, male_names: 800, surnames: 1500 };

// Extra entries that are especially common in human-chosen passwords but may be missing or ranked low.
const EXTRA = [
  'correcthorsebatterystaple', 'correcthorse', 'batterystaple', 'iloveyou', 'letmein', 'trustno1', 'changeme', 'welcome',
  'spring', 'summer', 'autumn', 'winter', 'january', 'february', 'march', 'april', 'may', 'june', 'july', 'august',
  'september', 'october', 'november', 'december', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday',
  'sunday', 'liverpool', 'arsenal', 'chelsea', 'everton', 'tottenham', 'manutd', 'manchester', 'united', 'celtic',
  'rangers', 'leeds', 'newcastle', 'barcelona', 'realmadrid', 'juventus', 'bayern', 'westham', 'villa', 'journal',
  'diary', 'secret', 'private', 'passphrase', 'mypassword', 'mydiary', 'myjournal',
];

const out = {};
for (const [name, n] of Object.entries(LIMITS)) out[name] = list(name).slice(0, n);
const seen = new Set(out.passwords);
const extra = EXTRA.filter((w) => !seen.has(w));

const here = dirname(fileURLToPath(import.meta.url));
const dest = resolve(here, '../src/lib/strengthData.ts');
const body = `/**
 * Dictionaries for the passphrase strength estimate (lib/strength.ts), loaded lazily on the pages
 * that set a passphrase. Generated by scripts/build-strength-data.mjs; do not edit by hand.
 *
 * Derived from the frequency lists of zxcvbn 4.4.2 (https://github.com/dropbox/zxcvbn),
 * Copyright (c) 2012-2016 Dan Wheeler and Dropbox, Inc., MIT License:
 * Permission is hereby granted, free of charge, to any person obtaining a copy of this software and
 * associated documentation files (the "Software"), to deal in the Software without restriction,
 * including without limitation the rights to use, copy, modify, merge, publish, distribute,
 * sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is
 * furnished to do so, subject to the following conditions: The above copyright notice and this
 * permission notice shall be included in all copies or substantial portions of the Software.
 * THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND.
 *
 * Each list is ordered by frequency (most common first) and comma-separated.
 */
export const PASSWORDS = ${JSON.stringify(out.passwords.join(','))};
export const EXTRA_PASSWORDS = ${JSON.stringify(extra.join(','))};
export const ENGLISH = ${JSON.stringify(out.english_wikipedia.join(','))};
export const FEMALE_NAMES = ${JSON.stringify(out.female_names.join(','))};
export const MALE_NAMES = ${JSON.stringify(out.male_names.join(','))};
export const SURNAMES = ${JSON.stringify(out.surnames.join(','))};
`;
writeFileSync(dest, body);
console.log(`wrote ${dest} (${body.length} bytes)`);
